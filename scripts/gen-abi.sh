#!/usr/bin/env bash
# Regenerates packages/abi/src/*.ts from the compiled Foundry artifacts. Contracts are the source of truth.
set -euo pipefail
cd "$(dirname "$0")/.."
forge build >/dev/null
out=packages/abi/src
for c in BscVaultV2 WantosBridgeV2 BridgeTimelock; do
  name=$(echo "$c" | awk '{print tolower(substr($0,1,1)) substr($0,2)}')
  { echo "// AUTO-GENERATED by scripts/gen-abi.sh from contracts/src/$c.sol — do not edit"
    printf 'export const %sAbi = ' "$name"
    printf '%s as const;\n' "$(forge inspect "$c" abi --json)"; } > "$out/$name.ts"
done
cat > "$out/index.ts" <<'EOT'
export { bscVaultV2Abi } from "./bscVaultV2";
export { wantosBridgeV2Abi } from "./wantosBridgeV2";
export { bridgeTimelockAbi } from "./bridgeTimelock";
EOT
echo "ABI generated"
